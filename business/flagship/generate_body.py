class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            self.notify('TOCEntry', (getattr(flowable, 'bookmark_level', 0),
                                     getattr(flowable, 'bookmark_text', ''),
                                     self.page,
                                     getattr(flowable, 'bookmark_key', '')))


def heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = p.bookmark_text = text
    p.bookmark_level = level
    p.bookmark_key = key
    return p


def section(story, text):
    story.append(CondPageBreak(H1_ORPHAN))
    story.append(heading(text, h1, 0))
    story.append(HRFlowable(width='100%', thickness=1.1, color=ACCENT,
                            spaceBefore=0, spaceAfter=10))


def callout(text):
    t = Table([[Paragraph(text, callout_txt)]], colWidths=[AVAIL * 0.96])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), BG_PAGE),
        ('LINEBEFORE', (0, 0), (0, -1), 3, ACCENT),
        ('TOPPADDING', (0, 0), (-1, -1), 9),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 9),
        ('LEFTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
    ]))
    return t


def workout_table(rows):
    """rows: list of (num, exercise, sets, rir, rest)"""
    data = [[Paragraph('<b>#</b>', th), Paragraph('<b>Exercise</b>', th),
             Paragraph('<b>Sets × Reps</b>', th), Paragraph('<b>RIR</b>', th),
             Paragraph('<b>Rest</b>', th)]]
    for r in rows:
        data.append([Paragraph(c, td) for c in r])
    ratios = [0.06, 0.47, 0.21, 0.11, 0.15]
    t = Table(data, colWidths=[r * AVAIL for r in ratios], hAlign='CENTER')
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('GRID', (0, 0), (-1, -1), 0.4, TEXT_MUTED),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


